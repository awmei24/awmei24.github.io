#!/usr/bin/env node
/*
 * Pulls published posts from substack and regenerates src/lib/posts.generated.ts.
 * Usage: npm run sync:substack  (then review the diff, commit, push)
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const PUBLICATION = "https://amandawangmei.substack.com";
const OUT_FILE = fileURLToPath(new URL("../src/lib/posts.generated.ts", import.meta.url));
const PAGE_SIZE = 50;
const WORDS_PER_MINUTE = 250;

async function fetchAllPosts() {
  const all = [];
  for (let offset = 0; ; offset += PAGE_SIZE) {
    const url = `${PUBLICATION}/api/v1/archive?sort=new&offset=${offset}&limit=${PAGE_SIZE}`;
    const res = await fetch(url, { headers: { Accept: "application/json" } });
    if (!res.ok) throw new Error(`substack returned ${res.status} for ${url}`);
    const page = await res.json();
    if (!Array.isArray(page)) throw new Error(`unexpected response shape from ${url}`);
    all.push(...page);
    if (page.length < PAGE_SIZE) return all;
  }
}

/* "2026-09-01T15:02:52Z" -> "sep 2026", matching the site's lowercase style */
function formatDate(iso) {
  return new Date(iso)
    .toLocaleString("en-US", { month: "short", year: "numeric", timeZone: "America/New_York" })
    .toLowerCase();
}

function toPost(p) {
  const minutes = Math.max(1, Math.round((p.wordcount ?? 0) / WORDS_PER_MINUTE));
  return {
    id: p.slug,
    title: p.title,
    date: formatDate(p.post_date),
    readTime: `${minutes} min`,
    excerpt: p.subtitle || p.description || "",
    link: p.canonical_url,
  };
}

const raw = await fetchAllPosts();
const posts = raw
  .filter((p) => p.type !== "thread" && p.slug && p.title && p.post_date)
  .sort((a, b) => b.post_date.localeCompare(a.post_date))
  .map(toPost);

if (posts.length === 0) {
  // never wipe the site's writing section because of a bad fetch
  throw new Error("no posts returned from substack; leaving existing file untouched");
}

const source = `/* AUTO-GENERATED by scripts/sync-substack.mjs — do not edit by hand. */
import type { Post } from "./content";

export const substackPosts: Post[] = ${JSON.stringify(posts, null, 2)};
`;

await writeFile(OUT_FILE, source);
console.log(`wrote ${posts.length} posts to src/lib/posts.generated.ts`);
for (const p of posts.slice(0, 5)) console.log(`  ${p.date.padEnd(9)} ${p.title}`);
